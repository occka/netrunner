//! Wallpapers for the app and dashboard backgrounds. Images the user picks are
//! copied into `<data>/wallpapers/` (so moving or deleting the original does
//! not break the background) and handed to the UI as data URLs; the UI's CSP
//! allows no file or remote images.

use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

use base64::Engine as _;
use serde::Serialize;

use crate::error::{AppError, AppResult};

const MAX_BYTES: u64 = 20 * 1024 * 1024;
const MAX_FILES: usize = 64;

const TYPES: &[(&str, &str)] = &[
    ("png", "image/png"),
    ("jpg", "image/jpeg"),
    ("jpeg", "image/jpeg"),
    ("webp", "image/webp"),
    ("gif", "image/gif"),
    ("bmp", "image/bmp"),
    ("avif", "image/avif"),
];

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Wallpaper {
    pub name: String,
    pub size_bytes: u64,
}

pub fn dir(data_dir: &Path) -> PathBuf {
    data_dir.join("wallpapers")
}

fn mime(name: &str) -> Option<&'static str> {
    let ext = name.rsplit('.').next()?.to_ascii_lowercase();
    TYPES.iter().find(|(e, _)| *e == ext).map(|(_, m)| *m)
}

/// Names are generated by [`import`]; anything else is refused, so a name can
/// never point outside the wallpapers folder.
fn check_name(name: &str) -> AppResult<()> {
    let ok = name.starts_with("wp-")
        && name.len() < 64
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '.')
        && name.matches('.').count() == 1
        && mime(name).is_some();
    if ok {
        Ok(())
    } else {
        Err(AppError::Invalid("invalid wallpaper name".into()))
    }
}

pub fn list(data_dir: &Path) -> AppResult<Vec<Wallpaper>> {
    let Ok(entries) = std::fs::read_dir(dir(data_dir)) else { return Ok(vec![]) };
    let mut out: Vec<Wallpaper> = entries
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            check_name(&name).ok()?;
            Some(Wallpaper { size_bytes: e.metadata().map(|m| m.len()).unwrap_or(0), name })
        })
        .collect();
    out.sort_by(|a, b| b.name.cmp(&a.name));
    Ok(out)
}

pub fn import(data_dir: &Path, source: &Path) -> AppResult<Wallpaper> {
    let ext = source
        .extension()
        .and_then(|e| e.to_str())
        .map(str::to_ascii_lowercase)
        .filter(|e| TYPES.iter().any(|(t, _)| t == e))
        .ok_or_else(|| AppError::Invalid("pick a PNG, JPEG, WebP, GIF, BMP or AVIF image".into()))?;
    let meta = std::fs::metadata(source)?;
    if !meta.is_file() {
        return Err(AppError::Invalid("not a file".into()));
    }
    if meta.len() > MAX_BYTES {
        return Err(AppError::Invalid("images up to 20 MB are supported".into()));
    }
    let target_dir = dir(data_dir);
    std::fs::create_dir_all(&target_dir)?;
    if list(data_dir)?.len() >= MAX_FILES {
        return Err(AppError::Invalid("remove some wallpapers first (64 at most)".into()));
    }
    let stamp = SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_millis()).unwrap_or(0);
    let name = (0..100)
        .map(|n| format!("wp-{stamp:x}-{n}.{ext}"))
        .find(|n| !target_dir.join(n).exists())
        .ok_or_else(|| AppError::Internal("cannot name the wallpaper".into()))?;
    std::fs::copy(source, target_dir.join(&name))?;
    Ok(Wallpaper { name, size_bytes: meta.len() })
}

pub fn delete(data_dir: &Path, name: &str) -> AppResult<()> {
    check_name(name)?;
    match std::fs::remove_file(dir(data_dir).join(name)) {
        Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e.into()),
        _ => Ok(()),
    }
}

pub fn data_url(data_dir: &Path, name: &str) -> AppResult<String> {
    check_name(name)?;
    let bytes = std::fs::read(dir(data_dir).join(name)).map_err(|_| AppError::NotFound("wallpaper was removed".into()))?;
    let mime = mime(name).unwrap_or("application/octet-stream");
    Ok(format!("data:{mime};base64,{}", base64::engine::general_purpose::STANDARD.encode(bytes)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wallpaper_lifecycle() {
        let root = std::env::temp_dir().join(format!("nr-wp-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        let src = root.join("my picture.PNG");
        std::fs::write(&src, [0x89, b'P', b'N', b'G', 1, 2, 3]).unwrap();
        let wp = import(&root, &src).unwrap();
        assert!(wp.name.starts_with("wp-") && wp.name.ends_with(".png"));
        assert_eq!(list(&root).unwrap().len(), 1);
        assert!(data_url(&root, &wp.name).unwrap().starts_with("data:image/png;base64,"));
        assert!(import(&root, &root.join("notes.txt")).is_err());
        assert!(data_url(&root, "../netrunner.db").is_err());
        assert!(data_url(&root, "wp-..\\x.png").is_err());
        delete(&root, &wp.name).unwrap();
        assert!(list(&root).unwrap().is_empty());
        let _ = std::fs::remove_dir_all(&root);
    }
}
